                "    out_node = nodes[out_idx]\n",
                "    \n",
                "    contributors = []\n",
                "    total_contrib = 0.0\n",
                "    \n",
                "    for idx, node in enumerate(nodes):\n",
                "        if idx == out_idx:\n",
                "            continue\n",
                "            \n",
                "        weight = float(node.get('weight', 0.8))\n",
                "        attn_val = float(attn[out_idx, idx]) if attn.shape[0] > out_idx and attn.shape[1] > idx else 0.5\n",
