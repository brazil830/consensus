                "class HGTAttentionLayer(nn.Module):\n",
                "    \"\"\"Heterogeneous Graph Transformer (HGT) Attention Layer.\"\"\"\n",
                "    def __init__(self, in_dim: int = 32, out_dim: int = 32, num_heads: int = 4):\n",
                "        super(HGTAttentionLayer, self).__init__()\n",
                "        self.num_heads = num_heads\n",
                "        self.out_dim = out_dim\n",
                "        self.q_proj = nn.Linear(in_dim, out_dim)\n",
                "        self.k_proj = nn.Linear(in_dim, out_dim)\n",
                "        self.v_proj = nn.Linear(in_dim, out_dim)\n",
                "        self.out_proj = nn.Linear(out_dim, out_dim)\n",
                "        \n",
                "    def forward(self, x: torch.Tensor):\n",
                "        # x shape: [num_nodes, in_dim]\n",
                "        q = self.q_proj(x)\n",
                "        k = self.k_proj(x)\n",
                "        v = self.v_proj(x)\n",
                "        \n",
                "        attn_weights = torch.matmul(q, k.transpose(-2, -1)) / (self.out_dim ** 0.5)\n",
                "        attn_probs = F.softmax(attn_weights, dim=-1)\n",
                "        output = torch.matmul(attn_probs, v)\n",
                "        return self.out_proj(output), attn_probs\n",
